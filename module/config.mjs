export function getWorldRule(key, fallback) {
  try {
    if (game?.settings?.settings?.has(`brp-uge.${key}`)) {
      return game.settings.get("brp-uge", key);
    }
  } catch (_err) {
    // ignore before settings init
  }
  return fallback;
}

export function getCampaignRules() {
  return {
    powerLevel: getWorldRule("campaignPowerLevel", "normal"),
    occupationBudgetMethod: getWorldRule("occupationBudgetMethod", "fixed"),
    startingSkillsSource: getWorldRule("startingSkillsSource", "all"),
    characteristicMethod: getWorldRule("characteristicMethod", "rolled"),
    useEdu: Boolean(getWorldRule("useEdu", false)),
    increasedPersonalSkillPoints: Boolean(getWorldRule("increasedPersonalSkillPoints", false)),
    useSanity: Boolean(getWorldRule("useSanity", false)),
    useFatigue: Boolean(getWorldRule("useFatigue", false)),
    useHitLocations: Boolean(getWorldRule("useHitLocations", false)),
    heroicHitPoints: Boolean(getWorldRule("heroicHitPoints", false)),
    categoryBonusMode: getWorldRule("categoryBonusMode", "standard"),
    creationSkillCap: Number(getWorldRule("creationSkillCap", 75) || 75),
    useCombatPhases: Boolean(getWorldRule("useCombatPhases", true)),
    useD10Initiative: Boolean(getWorldRule("useD10Initiative", false)),
    combatStatementOrder: getWorldRule("combatStatementOrder", "highFirst"),
    combatPowerTiming: getWorldRule("combatPowerTiming", "separate"),
    combatShowSceneHUD: Boolean(getWorldRule("combatShowSceneHUD", true)),
    combatRevealNpcIntent: Boolean(getWorldRule("combatRevealNpcIntent", false)),
    enabledPowerSystems: Object.fromEntries(["Magic","Sorcery","Psychic","Mutation","Superpower"].map(type => [type, Boolean(getWorldRule(`powerEnable${type}`, true))])),
    allowPlayerCharacterWizard: Boolean(getWorldRule("allowPlayerCharacterWizard", true))
  };
}

/** Disabling a power family only hides and prevents use; existing owned data is never deleted. */
export function isPowerSystemEnabled(type) {
  const systems = getCampaignRules().enabledPowerSystems;
  return systems[String(type || "Magic")] !== false;
}

import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const m=JSON.parse(read('system.json'));
assert.equal(m.version,'1.21.5');
assert.equal(m.id,'brp-uge');
assert.ok(!m.packs||m.packs.length===0);
assert.equal(Object.keys(m.documentTypes.Item).length,10);
for(const p of ['module/compendium-data.mjs','module/rulebook-reference-data.mjs','module/occupation-presets.mjs','module/library-seeds.mjs','module/rulebook-npcs.mjs','module/guides.mjs'])assert.ok(!existsSync(new URL('../'+p,import.meta.url)),p);
const main=read('brp-uge.mjs');
assert.doesNotMatch(main,/ensureBRPCompendiums|compendiumVersion|ensureBRPGuides|defaultStarterSkills|BRP_SKILL_KEYS/);
const actor=read('module/sheets/actor-sheet.mjs');
const wiz=read('module/apps/character-wizard.mjs');
const browser=read('module/compendium-browser.mjs');
for(const text of [main,actor,wiz,browser])assert.doesNotMatch(text,/BRP_COMPENDIUM_DATA|from ['"]\S*compendium-data\.mjs/);
assert.match(wiz,/const docs=await getLibraryDocuments\(\)/);
assert.match(wiz,/if\(prof.sourceUuid\)/);
assert.match(actor,/await getLibraryDocuments\(\{types:\['skill'\]/);
assert.match(browser,/getLibraryDocuments\(\{includeActors:true\}\)/);
assert.doesNotMatch(browser,/createCompendium|rebuildPacks|seed/);
const rules=read('module/rules/character-creation.mjs');
assert.match(rules,/generationFormula/);
assert.match(read('module/data-models.mjs'),/class OccupationDataModel/);
assert.match(read('module/data-models.mjs'),/class SkillDataModel/);
for(const file of ['templates/apps/compendium-browser.hbs','templates/apps/character-wizard.hbs','templates/actor/character-sheet.hbs'])assert.ok(read(file).length>100);
console.log('PASS v1.20: data-free engine manifest and bootstrap; Actor/Item/Wizard/browser maintained');

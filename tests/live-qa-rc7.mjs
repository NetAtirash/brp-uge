import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {correctedWoundRecovery} from '../module/rules/wound-correction.mjs';
const original=[{id:'one',firstAidAttempted:true,treated:true,treatmentMethod:'firstAid',treatmentResult:'success',recoveryHp:3,treatmentCount:1,healed:false,majorApplied:true},{id:'two',recoveryHp:2}];
const values={firstAidAttempted:false,treated:false,recoveryHp:1};
assert.throws(()=>correctedWoundRecovery(original,'one',values,false));
assert.throws(()=>correctedWoundRecovery(original,'one',{...values,recoveryHp:-1},true));
const updated=correctedWoundRecovery(original,'one',values,true);
assert.equal(updated[0].firstAidAttempted,false);
assert.equal(updated[0].treated,false);
assert.equal(updated[0].recoveryHp,1);
assert.equal(updated[0].treatmentResult,'');
assert.equal(updated[0].majorApplied,true);
assert.equal(updated[0].treatmentCount,1);
assert.equal(original[0].recoveryHp,3);
assert.deepEqual(updated[1],original[1]);
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
assert.match(read('module/apps/character-wizard.mjs'),/scrollable: \[".wiz-body", ".wiz-skill-list"/);
assert.match(read('module/sheets/actor-sheet.mjs'),/scrollable: \[".sheet-body"/);
assert.match(read('module/apps/specialty-presets-menu.mjs'),/if\(existing&&en===existing.en&&th===existing.th/);
assert.match(read('templates/actor/character-sheet.hbs'),/data-action="editWoundRecovery"/);
assert.match(read('styles/brp-live-qa-accessibility.css'),/comp-folder-tag/);
console.log('PASS: GM-only wound correction, source-row preservation, scroll and contrast contracts');

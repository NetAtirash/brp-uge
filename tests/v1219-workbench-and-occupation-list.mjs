import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const read=path=>readFileSync(resolve(root,path),'utf8');
const manifest=JSON.parse(read('system.json'));
assert.equal(manifest.version,'1.21.9');
assert.equal(manifest.styles.at(-1),'styles/brp-v1219-workbench.css');
for(const file of ['module/apps/skill-points-editor.mjs','module/skill-points-utils.mjs','styles/brp-v1219-workbench.css'])assert.ok(read(file).length>100,file);
const wizard=read('templates/apps/character-wizard.hbs');
const wizardLogic=read('module/apps/character-wizard.mjs');
assert.ok(wizard.includes('wiz-occupation-list')&&wizard.includes('wiz-occupation-row'));
assert.ok(wizard.includes('data-wiz-prof-search')&&wizard.includes('wiz-occupation-preview-rule'));
assert.ok(!wizard.includes('wiz-prof-card'),'Old oversized occupation cards must be removed');
assert.ok(wizardLogic.includes('plainDescription')&&wizardLogic.includes('professionFilter'));
const character=read('templates/actor/character-sheet.hbs');
const npc=read('templates/actor/npc-sheet.hbs');
const sheet=read('module/sheets/actor-sheet.mjs');
assert.ok(character.includes('data-action="openSkillPointsEditor"'));
assert.ok(npc.includes('data-action="openSkillPointsEditor"'));
assert.ok(sheet.includes('new BRPSkillPointsEditor({actor:this.document}).render(true)'));
assert.ok(character.includes('showSkillCategoryBonusColumn')&&character.includes('showSkillCategoryBonuses'));
assert.ok(sheet.includes("rules.categoryBonusMode !== 'none'"));
const {shouldShowCategoryBonus,shouldShowCategoryColumn,validateSkillPointValue,previewSkillTotal,buildSkillPointUpdates}=await import('../module/skill-points-utils.mjs');
assert.equal(shouldShowCategoryBonus('none',20),false);
assert.equal(shouldShowCategoryBonus('standard',0),false);
assert.equal(shouldShowCategoryBonus('standard',-4),true);
assert.equal(shouldShowCategoryColumn('none',[{bonus:30}]),false);
assert.equal(shouldShowCategoryColumn('standard',[{bonus:0},{bonus:0}]),false);
assert.equal(shouldShowCategoryColumn('standard',[{bonus:0},{bonus:3}]),true);
assert.equal(validateSkillPointValue('0'),0);
assert.equal(validateSkillPointValue('40'),40);
for(const invalid of ['', '-1', '1.5', 'abc', null, undefined])assert.equal(validateSkillPointValue(invalid),null);
const system={total:48,occupationBonus:15,personalBonus:10,categoryBonus:0,trainingTotal:0};
assert.equal(previewSkillTotal(system,20,15),58);
assert.equal(previewSkillTotal({...system,fixedRating:65},20,15),48);
const actorItems=[{id:'s1',type:'skill',name:'Science (Astronomy)',system},{id:'s2',type:'skill',name:'Science (Geology)',system:{occupationBonus:0,personalBonus:0}}];
const draft=new Map([['s1',{occupation:20,personal:15}],['s2',{occupation:0,personal:0}]]);
assert.deepEqual(buildSkillPointUpdates(actorItems,draft),[{_id:'s1','system.occupationBonus':20,'system.personalBonus':15}]);
assert.throws(()=>buildSkillPointUpdates(actorItems,new Map([['s1',{occupation:-1,personal:5}]])),/Invalid Skill points/);
assert.ok(read('module/apps/skill-points-editor.mjs').includes("updateEmbeddedDocuments('Item',changes)"));
// The runtime editor is native Foundry ApplicationV2; mock it here to verify
// initial HTML and the no-bonus display without requiring a Foundry browser.
globalThis.foundry={applications:{api:{ApplicationV2:class{setPosition(){} _onRender(){}}}}};
const rules=new Map([['brp-uge.categoryBonusMode',true]]);
globalThis.game={settings:{settings:{has:key=>rules.has(key)},get(_ns,key){return ({uiLanguage:'th',categoryBonusMode:'none'})[key] ?? false;}}};
const {BRPSkillPointsEditor}=await import('../module/apps/skill-points-editor.mjs');
const actor={name:'Test',isOwner:true,system:{characteristics:{int:{value:10}},derived:{categoryBonuses:{combat:0,mental:0}}},
  items:{filter(fn){return actorItems.filter(fn)},get(id){return actorItems.find(x=>x.id===id)}}};
const editor=new BRPSkillPointsEditor({actor});
const markup=await editor._renderHTML();
assert.ok(markup.includes('Science (Astronomy)'));
assert.ok(markup.includes('brp-points-row')&&markup.includes('without-category'));
assert.ok(markup.includes('data-point-field="occupation"')&&markup.includes('data-point-field="personal"'));
assert.ok(!markup.includes('Category Bonus'));
console.log('PASS v1.21.9: occupation catalog, full-viewport skill allocation, bonus visibility, draft validation and batched Item updates');
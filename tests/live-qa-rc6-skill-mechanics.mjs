import assert from 'node:assert/strict';
import {calculateSkillBase,canGainExperience,canRecordAdvancement} from '../module/rules/skill-mechanics.mjs';
const skill=(family,specialty,formula='',base=0)=>({type:'skill',name:family+' ('+specialty+')',system:{nameEn:family+' ('+specialty+')',specialtyFamily:family,specialty,baseFormula:formula,base}});
const reputation=skill('Status','Guild','',15);
assert.equal(canGainExperience(reputation),false);
assert.equal(canRecordAdvancement(reputation,'experience',true),false);
assert.equal(canRecordAdvancement(reputation,'training',true),false);
assert.equal(canRecordAdvancement(reputation,'manual',false),false);
assert.equal(canRecordAdvancement(reputation,'reputation',true),true);
const native=skill('Language','Own','INT*5'),foreign=skill('Language','Foreign','',0);
const literacy=skill('Literacy','Own','LANGUAGE_BASE'),other=skill('Literacy','Foreign','LANGUAGE_BASE');
assert.equal(calculateSkillBase(native,{int:15,edu:10},{useEdu:true}),75);
assert.equal(calculateSkillBase(native,{int:12,edu:16},{useEdu:true}),80);
assert.equal(calculateSkillBase(literacy,{int:15,edu:10},{useEdu:true},[native,foreign]),75);
assert.equal(calculateSkillBase(other,{int:15,edu:10},{useEdu:true},[native,foreign]),0);
assert.equal(calculateSkillBase(literacy,{int:15},{},[foreign]),0);
assert.equal(calculateSkillBase(literacy,{int:15},{},[native,native]),0);
assert.equal(calculateSkillBase(skill('Literacy','Own','',0),{int:15},{},[native]),0);
assert.equal(canGainExperience(native),true);
console.log('PASS: reputation-only advancement, matching language base, shared Wizard/Actor formula');

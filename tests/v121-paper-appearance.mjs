import assert from 'node:assert/strict';
import {readFileSync, existsSync} from 'node:fs';
import {PAPER_THEMES, normalizePaperTheme, currentPaperTheme, applyPaperTheme} from '../module/paper-appearance.mjs';
const read=f=>readFileSync(new URL('../'+f,import.meta.url),'utf8');
const m=JSON.parse(read('system.json'));
assert.equal(m.version,'1.21.8');
assert.deepEqual(Object.keys(PAPER_THEMES),['light','dark']);
assert.equal(normalizePaperTheme('neon'),'light');
assert.equal(normalizePaperTheme('dark'),'dark');
assert.equal(currentPaperTheme({get:()=> 'dark'}),'dark');
const html={dataset:{brpGenre:'addon-controlled'}};
assert.equal(applyPaperTheme({get:()=> 'light'},html),'light');
assert.deepEqual(html.dataset,{brpGenre:'addon-controlled',brpTheme:'light'});
assert.ok(m.styles.includes('styles/brp-paper.css') && m.styles.includes('styles/brp-v1216-usability.css') && m.styles.at(-1)==='styles/brp-v1218-specialties.css');
assert.match(read('styles/brp-paper.css'),/data-brp-theme="light"/);
assert.match(read('styles/brp-paper.css'),/data-brp-theme="dark"/);
assert.ok(!existsSync(new URL('../assets/themes',import.meta.url)));
assert.ok(!existsSync(new URL('../assets/icons/scifi',import.meta.url)));
assert.ok(!existsSync(new URL('../module/theme-system.mjs',import.meta.url)));
const engine=read('brp-uge.mjs');
for(const token of ['sheetGenre','sheetVariation','sheetTheme','iconTheme','renderSettingsConfig','legacyThemeAppearance'])assert.doesNotMatch(engine,new RegExp('register\\([^)]*'+token));
assert.match(engine,/game\.settings\.register\('brp-uge', 'paperTheme'/);
assert.match(engine,/registerIconResolver/);
for(const path of ['templates/actor/character-sheet.hbs','templates/actor/npc-sheet.hbs'])assert.match(read(path),/data-action="togglePaperTheme"/);
for(const path of ['module/sheets/actor-sheet.mjs','module/sheets/item-sheet.mjs','module/apps/character-wizard.mjs','module/compendium-browser.mjs'])assert.doesNotMatch(read(path),/['"]theme-dark['"]/);
assert.match(read('module/library-taxonomy.mjs'),/iconResolver/);
console.log('PASS 1.21 light/dark notebook and optional genre separation');
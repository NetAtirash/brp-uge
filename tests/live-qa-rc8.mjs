import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {buildSpecialtyRegistry,specialtyLabelIssue,specialtyDraftState,specialtyEditorState} from '../module/specialty-registry.mjs';
import {correctedWoundRecovery,woundTreatmentState} from '../module/rules/wound-correction.mjs';
const item={uuid:'Compendium.example.skills.Item.aaaaaaaaaaaaaaaa',type:'skill',name:'Example (...)',system:{nameEn:'Example (...)',specialtyFamily:'Example',isSpecialtyTemplate:true,specialtyDefaults:[{key:'generic',en:'Generic heading',th:'ตัวอย่าง (ระบุชนิด)',enabled:false},{key:'one',en:'Concrete',th:'ตัวอย่าง/ชนิด',enabled:true}]}};
const rows=buildSpecialtyRegistry([item])[0].options;
const disabled=rows.find(o=>o.bookKey==='generic');
assert.equal(specialtyEditorState(disabled),'hidden');
assert.equal(specialtyDraftState('hidden','enabled',false),'hidden');
assert.equal(specialtyDraftState('hidden','enabled',true),'enabled');
assert.equal(specialtyLabelIssue(disabled.en,disabled.th),'thai');
assert.equal(specialtyLabelIssue('Concrete','ตัวอย่าง/ชนิด'),null);
const old={families:{example:{bookOverrides:{generic:{en:'Generic heading',th:'ตัวอย่าง (ระบุชนิด)',state:'enabled'}}}}};
const pending=buildSpecialtyRegistry([item],old)[0].options.find(o=>o.bookKey==='generic');
assert.equal(specialtyEditorState(pending),'review');
assert.equal(pending.hidden,true);
assert.equal(old.families.example.bookOverrides.generic.state,'enabled');
const approved={families:{example:{bookOverrides:{generic:{en:'Specific skill',th:'เฉพาะทาง',state:'enabled'}}}}};
assert.equal(buildSpecialtyRegistry([item],approved)[0].options.find(o=>o.bookKey==='generic').hidden,false);
const w={id:'one',treated:false,firstAidAttempted:true,treatmentResult:'failure',treatmentMethod:'firstAid',recoveryHp:0};
const [corrected]=correctedWoundRecovery([w],'one',{firstAidAttempted:true,treated:true,recoveryHp:0},true);
assert.equal(corrected.treatmentResult,'');
assert.equal(woundTreatmentState(corrected,true).key,'treated');
assert.equal(woundTreatmentState({...corrected,healed:true}).key,'resolved');
assert.equal(woundTreatmentState(w).key,'untreated');
assert.equal(w.treatmentResult,'failure');
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
assert.doesNotMatch(read('templates/apps/character-wizard.hbs'),/p\.wealthLabel/);
assert.match(read('templates/apps/character-wizard.hbs'),/brp-personality-readout/);
assert.match(read('templates/actor/character-sheet.hbs'),/w\.treatmentState\.label/);
assert.match(read('styles/brp-live-qa-accessibility.css'),/brp-wound-actions\{[^}]*flex-wrap:nowrap/);
console.log('PASS: disabled source state, bilingual validation, explicit approval, wound treatment state and scoped QA UI contracts');

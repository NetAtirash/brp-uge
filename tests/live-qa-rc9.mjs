import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {choiceShortageDetails,validateChoicePlan} from '../module/creation-template-integration.mjs';
const group={count:1,options:[{kind:'specialty',familyKey:'example',specialtyKey:'missing'}]};

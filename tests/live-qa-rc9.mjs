const form=sheet.slice(sheet.indexOf('<form class="brp-macro-form brp-wound-entry">')).split('</form>')[0];
assert.match(form,/list="brp-wound-presets"/);
assert.match(form,/list="brp-body-presets"/);
assert.match(form,/<select name="severity">/);
assert.doesNotMatch(form,/brp-wound-picker|fa-chevron-down/);
assert.doesNotMatch(read('styles/brp-live-qa-accessibility.css'),/brp-wound-picker/);
assert.match(read('templates/apps/character-wizard.hbs'),/personalityHasShortage.*refreshWizardSpecialties/);

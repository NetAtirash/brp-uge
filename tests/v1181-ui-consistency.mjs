import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const root = new URL('../', import.meta.url);
const read = (file) => readFileSync(new URL(file, root), 'utf8');
const pack = JSON.parse(read('system.json'));
assert.ok(['1.18.1','1.18.2','1.18.3','1.19.0','1.20.0','1.21.8'].includes(pack.version));
assert.ok(pack.styles.includes('styles/brp-ui-consistency.css'));
const template = read('templates/actor/character-sheet.hbs');
assert.match(template, /class="brp-skill-id-cell"/);
assert.match(template, /class="skill-edit-heading"/);
assert.match(template, /class="item-row skill-edit-row"/);
const editRow = template.slice(template.indexOf('<li class="item-row skill-edit-row"'), template.indexOf('</li>', template.indexOf('<li class="item-row skill-edit-row"')));
assert.equal((editRow.match(/data-action="toggleExp"/g) ?? []).length, 1);
assert.equal((editRow.match(/data-action="shareEntry"/g) ?? []).length, 1);
assert.equal((editRow.match(/data-item-field="system\.(?:occupationBonus|personalBonus)"/g) ?? []).length, 2);
assert.equal((editRow.match(/data-action="rollSkill"/g) ?? []).length, 1);
assert.match(template,/class="brp-skill-search-field"/);
assert.match(template,/fa-magnifying-glass/);
assert.doesNotMatch(template,/placeholder="🔍/);
assert.match(template,/\{\{#if isGM\}\}/);
const css = read('styles/brp-ui-consistency.css');
for (const token of ['--brp-skill-columns','.brp-stat-effective-value','.brp-skill-id-cell','.brp-skill-search-field','.skill-edit-heading','.skill-edit-row','.brp-roll-value','--brp-control-radius']) assert.ok(css.includes(token), token);
assert.match(read('module/sheets/actor-sheet.mjs'),/context\.isGM = Boolean\(game\.user\?\.isGM\)/);
console.log('PASS v1.18.1 editorial alignment, player copy and input hierarchy');